"""Database connection adapter — SQLite (dev) or Postgres (DATABASE_URL / RDS).

Call sites keep sqlite-style ``?`` placeholders and Row indexing. When
``DATABASE_URL`` starts with ``postgres``, connections use psycopg with
compatibility shims (placeholder rewrite, PRAGMA table_info, executescript).
"""

from __future__ import annotations

import os
import re
import sqlite3
import time
from pathlib import Path
from typing import Any, Iterable

BASE_DIR = Path(__file__).resolve().parent
DEFAULT_SQLITE_PATH = BASE_DIR / "marketqr.db"

# Re-export error types so call sites can catch both backends.
IntegrityError = sqlite3.IntegrityError
OperationalError = sqlite3.OperationalError

try:
    import psycopg
    from psycopg import errors as _pg_errors
    from psycopg.rows import dict_row

    IntegrityError = (sqlite3.IntegrityError, _pg_errors.IntegrityError)  # type: ignore[misc, assignment]
    OperationalError = (sqlite3.OperationalError, _pg_errors.OperationalError)  # type: ignore[misc, assignment]
except ImportError:  # pragma: no cover
    psycopg = None  # type: ignore[assignment]
    dict_row = None  # type: ignore[assignment]


def database_url() -> str:
    return (os.environ.get("DATABASE_URL") or "").strip()


def using_postgres() -> bool:
    url = database_url().lower()
    return url.startswith("postgres://") or url.startswith("postgresql://")


def sqlite_path() -> Path:
    raw = (os.environ.get("SQLITE_PATH") or "").strip()
    return Path(raw) if raw else DEFAULT_SQLITE_PATH


_QMARK_RE = re.compile(r"(?<!')\?(?!')")
_PRAGMA_INFO_RE = re.compile(r"^\s*PRAGMA\s+table_info\((\w+)\)\s*$", re.I)
_PRAGMA_FK_LIST_RE = re.compile(r"^\s*PRAGMA\s+foreign_key_list\((\w+)\)\s*$", re.I)
_AUTOINCREMENT_RE = re.compile(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", re.I)
_COLLATE_NOCASE_RE = re.compile(r"\s+COLLATE\s+NOCASE", re.I)


_SQLITE_MASTER_NAME_RE = re.compile(
    r"SELECT\s+name\s+FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'"
    r"(?:\s+AND\s+name\s+NOT\s+LIKE\s+'sqlite_%')?"
    r"(?:\s+AND\s+name\s*=\s*\?)?"
    r"(?:\s+ORDER\s+BY\s+name)?",
    re.I,
)
_SQLITE_MASTER_EXISTS_RE = re.compile(
    r"SELECT\s+1\s+FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'\s+AND\s+name\s*=\s*\?",
    re.I,
)


def _rewrite_sqlite_catalog(sql: str) -> str:
    """Map sqlite_master probes to Postgres catalog queries."""
    if "sqlite_master" not in sql.lower():
        return sql
    if _SQLITE_MASTER_EXISTS_RE.search(sql):
        return _SQLITE_MASTER_EXISTS_RE.sub(
            "SELECT 1 FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_name = ?",
            sql,
        )
    if _SQLITE_MASTER_NAME_RE.search(sql):
        # Keep optional name=? filter if present in original.
        if re.search(r"\bname\s*=\s*\?", sql, re.I):
            return (
                "SELECT tablename AS name FROM pg_tables "
                "WHERE schemaname = 'public' AND tablename = ?"
            )
        return "SELECT tablename AS name FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename"
    return sql


def _to_pg_sql(sql: str) -> str:
    sql = _rewrite_sqlite_catalog(sql)
    sql = _AUTOINCREMENT_RE.sub("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
    sql = _COLLATE_NOCASE_RE.sub("", sql)
    if re.search(r"\bINSERT\s+OR\s+IGNORE\b", sql, re.I):
        sql = re.sub(r"\bINSERT\s+OR\s+IGNORE\b", "INSERT", sql, flags=re.I)
        if "ON CONFLICT" not in sql.upper():
            sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    elif re.search(r"\bINSERT\s+OR\s+REPLACE\b", sql, re.I):
        sql = re.sub(r"\bINSERT\s+OR\s+REPLACE\b", "INSERT", sql, flags=re.I)
        if "ON CONFLICT" not in sql.upper():
            sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    # SQLite CURRENT_TIMESTAMP as TEXT is fine on PG too for TIMESTAMP-ish columns stored as TEXT.
    return _QMARK_RE.sub("%s", sql)


class _Row(dict):
    """dict that also supports integer index and .keys() like sqlite3.Row."""

    def __getitem__(self, key):  # type: ignore[override]
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)

    def keys(self):  # type: ignore[override]
        return super().keys()


class _CursorResult:
    def __init__(self, rows: list[_Row], lastrowid: int | None = None, rowcount: int = -1):
        self._rows = rows
        self.lastrowid = lastrowid
        self.rowcount = rowcount
        self._i = 0

    def fetchone(self):
        if self._i >= len(self._rows):
            return None
        row = self._rows[self._i]
        self._i += 1
        return row

    def fetchall(self):
        rest = self._rows[self._i :]
        self._i = len(self._rows)
        return rest

    def __iter__(self):
        return iter(self.fetchall())


_INSERT_TABLE_RE = re.compile(
    r"^\s*INSERT\s+(?:OR\s+\w+\s+)?INTO\s+([A-Za-z_][\w]*)",
    re.I,
)
# Tables known to lack an `id` column — skip RETURNING after first miss.
_TABLES_WITHOUT_ID: set[str] = set()


class PostgresConnection:
    """psycopg connection with sqlite-like execute/executescript surface."""

    def __init__(self, raw):
        self._raw = raw
        self._lastrowid: int | None = None

    def execute(self, sql: str, params: Iterable[Any] | None = None):
        sql = sql.strip()
        m = _PRAGMA_INFO_RE.match(sql)
        if m:
            return self._table_info(m.group(1))
        fk = _PRAGMA_FK_LIST_RE.match(sql)
        if fk:
            # Fresh Postgres has no SQLite-style rebuild path; empty list is safe.
            return _CursorResult([])

        insert_table_m = _INSERT_TABLE_RE.match(sql)
        insert_table = insert_table_m.group(1).lower() if insert_table_m else None

        pg_sql = _to_pg_sql(sql)
        params = tuple(params) if params is not None else ()

        # Capture identity for INSERT without RETURNING (skip tables without id).
        want_id = (
            bool(re.match(r"^\s*INSERT\s+INTO\s+", pg_sql, re.I))
            and "RETURNING" not in pg_sql.upper()
            and (not insert_table or insert_table not in _TABLES_WITHOUT_ID)
        )
        if want_id and not pg_sql.rstrip().endswith(";"):
            # Best-effort: append RETURNING id when table has id column.
            pg_sql = pg_sql.rstrip() + " RETURNING id"

        with self._raw.cursor(row_factory=dict_row) as cur:
            used_returning = want_id and "RETURNING id" in pg_sql
            if used_returning:
                cur.execute("SAVEPOINT sp_mq_returning")
            try:
                cur.execute(pg_sql, params)
            except Exception as exc:
                if used_returning:
                    cur.execute("ROLLBACK TO SAVEPOINT sp_mq_returning")
                    if insert_table and "column \"id\" does not exist" in str(exc).lower():
                        _TABLES_WITHOUT_ID.add(insert_table)
                    pg_sql = _to_pg_sql(sql)
                    cur.execute(pg_sql, params)
                    self._lastrowid = None
                    rows: list[_Row] = []
                    if cur.description:
                        rows = [_Row(r) for r in cur.fetchall()]
                    return _CursorResult(rows, lastrowid=None, rowcount=cur.rowcount)
                raise
            finally:
                if used_returning:
                    try:
                        cur.execute("RELEASE SAVEPOINT sp_mq_returning")
                    except Exception:
                        pass

            self._lastrowid = None
            rows = []
            if cur.description:
                fetched = cur.fetchall()
                rows = [_Row(r) for r in fetched]
                if want_id and rows and "id" in rows[0]:
                    self._lastrowid = int(rows[0]["id"])
                    # Mimic sqlite INSERT: callers rarely fetch RETURNING rows
                    if "RETURNING id" in pg_sql and len(rows) == 1 and set(rows[0].keys()) == {"id"}:
                        rows = []
            return _CursorResult(rows, lastrowid=self._lastrowid, rowcount=cur.rowcount)

    def executemany(self, sql: str, seq_of_params):
        pg_sql = _to_pg_sql(sql)
        with self._raw.cursor() as cur:
            cur.executemany(pg_sql, list(seq_of_params))
            return _CursorResult([], rowcount=cur.rowcount)

    def executescript(self, script: str) -> None:
        # Strip line comments; split on semicolons outside of naive strings.
        cleaned = re.sub(r"--[^\n]*", "", script)
        parts = [p.strip() for p in cleaned.split(";") if p.strip()]
        for part in parts:
            # Skip SQLite-only pragmas
            if part.upper().startswith("PRAGMA"):
                continue
            self.execute(part)

    def _table_info(self, table: str) -> _CursorResult:
        with self._raw.cursor(row_factory=dict_row) as cur:
            cur.execute(
                """
                SELECT column_name AS name,
                       data_type AS type,
                       CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
                       column_default AS dflt_value,
                       CASE WHEN EXISTS (
                         SELECT 1 FROM information_schema.table_constraints tc
                         JOIN information_schema.key_column_usage kcu
                           ON tc.constraint_name = kcu.constraint_name
                          AND tc.table_schema = kcu.table_schema
                         WHERE tc.table_name = %s
                           AND tc.constraint_type = 'PRIMARY KEY'
                           AND kcu.column_name = c.column_name
                       ) THEN 1 ELSE 0 END AS pk
                FROM information_schema.columns c
                WHERE table_schema = 'public' AND table_name = %s
                ORDER BY ordinal_position
                """,
                (table, table),
            )
            rows = [_Row(r) for r in cur.fetchall()]
        return _CursorResult(rows)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()

    @property
    def lastrowid(self):
        return self._lastrowid


def _configure_sqlite(connection: sqlite3.Connection) -> None:
    connection.execute("PRAGMA foreign_keys=ON")
    connection.execute("PRAGMA journal_mode=WAL")
    connection.execute("PRAGMA busy_timeout=60000")
    connection.execute("PRAGMA synchronous=NORMAL")


def _iam_auth_enabled() -> bool:
    return (os.environ.get("DATABASE_IAM_AUTH") or "").strip().lower() in ("1", "true", "yes")


def _rds_iam_token(host: str, port: int, user: str) -> str:
    """Short-lived IAM DB auth token (~15 min). Requires AWS credentials + rds-db:connect."""
    try:
        import boto3
    except ImportError as exc:  # pragma: no cover
        raise RuntimeError(
            "DATABASE_IAM_AUTH=1 requires boto3. pip install boto3"
        ) from exc
    region = (
        (os.environ.get("AWS_REGION") or os.environ.get("AWS_DEFAULT_REGION") or "ap-southeast-2")
        .strip()
    )
    client = boto3.client("rds", region_name=region)
    return client.generate_db_auth_token(
        DBHostname=host,
        Port=port,
        DBUsername=user,
        Region=region,
    )


def sqlite_file_uri(path: Path) -> str:
    """Build a SQLite ``file:`` URI with a percent-encoded path.

    ``%``, ``#``, and ``?`` are reserved in URIs. Any connection opened with
    ``uri=True`` must use this helper instead of interpolating the raw path.
    """
    from urllib.parse import quote

    text = Path(path).resolve().as_posix()
    quoted = quote(text, safe="/")
    if quoted.startswith("/"):
        return "file://" + quoted
    return "file:///" + quoted


def open_connection(sqlite_file: Path | None = None):
    """Open a new DB connection (caller owns close/commit)."""
    if using_postgres():
        if psycopg is None:
            raise RuntimeError("DATABASE_URL is set but psycopg is not installed. pip install 'psycopg[binary]'")
        from urllib.parse import unquote, urlparse

        url = database_url()
        if url.startswith("postgres://"):
            url = "postgresql://" + url[len("postgres://") :]
        if _iam_auth_enabled():
            parsed = urlparse(url)
            host = parsed.hostname or ""
            port = int(parsed.port or 5432)
            user = unquote(parsed.username or "postgres")
            dbname = (parsed.path or "/postgres").lstrip("/") or "postgres"
            token = _rds_iam_token(host, port, user)
            raw = psycopg.connect(
                host=host,
                port=port,
                dbname=dbname,
                user=user,
                password=token,
                sslmode="require",
                connect_timeout=20,
            )
        else:
            raw = psycopg.connect(url, connect_timeout=15)
        raw.autocommit = False
        return PostgresConnection(raw)

    path = Path(sqlite_file) if sqlite_file else sqlite_path()
    # Filesystem path, not a URI. URI connections must go through sqlite_file_uri().
    connection = sqlite3.connect(path, timeout=60, check_same_thread=False)
    connection.row_factory = sqlite3.Row
    _configure_sqlite(connection)
    return connection


def commit_with_retry(connection, *, attempts: int = 8) -> None:
    for attempt in range(attempts):
        try:
            connection.commit()
            return
        except OperationalError as exc:
            msg = str(exc).lower()
            if "locked" not in msg or attempt >= attempts - 1:
                raise
            connection.rollback()
            time.sleep(min(0.05 * (2**attempt), 1.0))
