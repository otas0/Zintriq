    def test_d5_public_css_no_hex_outside_tokens(self):
        import re

        hex_re = re.compile(r"(?<![0-9a-fA-F])#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b")
        roots = [
            ROOT / "static" / "css",
        ]
        allow_prefix = ("tokens",)  # tokens.css, tokens-marketing.css
        offenders = []
        for folder in roots:
            for path in folder.rglob("*.css"):
                if path.name.startswith(allow_prefix):
                    continue
                text = path.read_text(encoding="utf-8")
                # strip comments
                text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
                hits = hex_re.findall(text)
                if hits:
                    offenders.append(f"{path.relative_to(ROOT)}:{hits[:5]}")
        self.assertEqual(offenders, [], msg="; ".join(offenders))

