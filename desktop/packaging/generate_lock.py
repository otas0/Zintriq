#!/usr/bin/env python3
"""Write requirements-desktop.lock.txt with hashes from PyPI (build-time only)."""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IN_FILE = ROOT / "requirements-desktop.in"


def _packages() -> list:
    raw = subprocess.check_output([sys.executable, "-m", "pip", "freeze"], text=True)
    names = []
    for line in raw.splitlines():
        if not line or line.startswith("#") or line.startswith("-e ") or " @ " in line:
            continue
        if "==" not in line:
            continue
        name, version = line.split("==", 1)
        names.append((name.strip(), version.strip()))
    wanted_prefixes = _wanted()
    return [(name, version) for name, version in names if _keep(name, wanted_prefixes)]


def _wanted() -> set:
    text = IN_FILE.read_text(encoding="utf-8")
    found = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name = re.split(r"[<>=~\[]", line, maxsplit=1)[0].strip().lower()
        if name:
            found.add(name)
    found.update({"waitress", "pyinstaller", "pyinstaller-hooks-contrib", "altgraph", "macholib", "packaging", "pillow", "qrcode"})
    return found


def _keep(name: str, wanted: set) -> bool:
    lower = name.lower().replace("_", "-")
    if lower in {"pip"}:
        return False
    if lower.startswith("psycopg"):
        return False
    seeds = {
        "flask",
        "babel",
        "cryptography",
        "qrcode",
        "pillow",
        "waitress",
        "pyinstaller",
        "jinja2",
        "werkzeug",
        "itsdangerous",
        "click",
        "markupsafe",
        "blinker",
        "cffi",
        "pycparser",
        "altgraph",
        "macholib",
        "packaging",
        "pyinstaller-hooks-contrib",
        "setuptools",
        "wheel",
        "importlib-metadata",
        "zipp",
        "typing-extensions",
    }
    return lower in seeds or lower in wanted or any(lower.startswith(item) for item in wanted)


def _pypi_files(name: str, version: str) -> list:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:
        payload = json.loads(response.read().decode("utf-8"))
    urls = payload.get("urls") or []
    hashes = []
    for item in urls:
        sha = (item.get("digests") or {}).get("sha256")
        filename = item.get("filename") or ""
        if sha and filename:
            hashes.append((filename, sha))
    return hashes


def main() -> int:
    packages = _packages()
    lines = [
        "# Hashed lock for desktop freeze. Generated by desktop/packaging/generate_lock.py.",
        "# Install: python -m pip install --require-hashes -r requirements-desktop.lock.txt",
        "",
    ]
    for name, version in packages:
        files = _pypi_files(name, version)
        if not files:
            print(f"no files for {name}=={version}", file=sys.stderr)
            return 1
        lines.append(f"{name}=={version} \\")
        for index, (_filename, sha) in enumerate(files):
            suffix = " \\" if index < len(files) - 1 else ""
            lines.append(f"    --hash=sha256:{sha}{suffix}")
        lines.append("")
    dest = ROOT / "requirements-desktop.lock.txt"
    dest.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {dest} ({len(packages)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
